def load_user_themes() -> dict:
    """Kullanıcı temalarını yükler."""
    try:
        if os.path.exists(THEMES_USER_FILE):
            with open(THEMES_USER_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
    except Exception:
        pass
    return {}


def all_themes() -> dict:
    """Tüm temaları (yerleşik + kullanıcı) döndürür."""
    t = dict(THEMES)
    t.update(load_user_themes())
    return t


def save_user_theme(name: str, theme: dict) -> bool:
    """Kullanıcı temasını kaydeder."""
    try:
        user = load_user_themes()
        user[name] = theme
        atomic_write(THEMES_USER_FILE,
                     json.dumps(user, indent=2, ensure_ascii=False))
        return True
    except Exception:
        return False


def delete_user_theme(name: str) -> bool:
    """Kullanıcı temasını siler."""
    try:
        user = load_user_themes()
        user.pop(name, None)
        atomic_write(THEMES_USER_FILE,
                     json.dumps(user, indent=2, ensure_ascii=False))
        return True
    except Exception:
        return False

